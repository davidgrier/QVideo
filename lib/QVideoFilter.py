'''Base classes for image-processing filters in the QVideo filter pipeline.'''
from __future__ import annotations
import dataclasses
import logging
import numpy as np
from qtpy import QtCore, QtWidgets
from QVideo.lib.videotypes import Image
from QVideo.lib.imageops import to8bit
import pyqtgraph as pg


logger = logging.getLogger(__name__)

__all__ = ['FilterCode', 'GRAY_LINES', 'renderPipeline', 'prepare',
           'VideoFilter', 'QVideoFilter']


@dataclasses.dataclass
class FilterCode:
    '''Code fragment emitted by a filter's :meth:`~VideoFilter.to_code` method.

    Attributes
    ----------
    imports : frozenset[str]
        Complete import lines required by *lines*, e.g. ``'import cv2'``.
        Any collection of lines will do; it becomes a frozenset.
    lines : list[str]
        Source lines (no leading indentation) that implement one filter
        step.  The variable ``image`` holds the current frame on entry
        and must hold the result on exit.
    comment : str
        Optional one-line description included as a comment above the
        generated code block.
    '''

    imports: frozenset[str]
    lines: list[str]
    comment: str = ''

    def __post_init__(self) -> None:
        self.imports = frozenset(self.imports)


#: The lines of a :class:`FilterCode` that make ``image`` gray.
GRAY_LINES = ('if image.ndim == 3:',
              '    image = cv2.cvtColor(image, cv2.COLOR_RGB2GRAY)')


def renderPipeline(fragments: list[FilterCode], skipped: list[str]) -> str:
    '''Return the source of a module that applies *fragments* in order.

    Parameters
    ----------
    fragments : list[FilterCode]
        Code of the filters to apply, in pipeline order.
    skipped : list[str]
        Names of filters that have no code (stateful filters); they are
        listed in a comment.

    Returns
    -------
    str
        Source of a ``filter.py`` module defining
        ``filter(image: np.ndarray) -> np.ndarray``.
    '''
    imports = {'import numpy as np'}.union(*(f.imports for f in fragments))
    body = []
    for fragment in fragments:
        if fragment.comment:
            body.append(f'    # {fragment.comment}')
        body.extend(f'    {line}' for line in fragment.lines)
        body.append('')
    body.append('    return image')
    parts = ["'''Image-processing pipeline generated by QVideo.'''", '',
             *sorted(imports), '', '']
    if skipped:
        parts += ['# NOTE: the following filters are stateful and were '
                  'omitted:',
                  *(f'#   {name}' for name in skipped), '', '']
    parts += ['def filter(image: np.ndarray) -> np.ndarray:', *body]
    return '\n'.join(parts) + '\n'


def prepare(video_filter: object, frame: Image,
            levels: tuple[float, float] | None
            ) -> tuple[Image, tuple[float, float] | None]:
    '''Return *frame* as *video_filter* wants it, and its levels.

    A ``uint16`` frame goes to a :attr:`~VideoFilter.deep` filter as it is,
    and the filter is told the *levels*.  Any other filter gets the frame
    scaled to ``uint8`` between its *levels*, which are then ``None``.  This
    is what every place that applies filters does, so that a filter sees
    the same frame in the pipeline, in a rack and on a notebook camera.

    Parameters
    ----------
    video_filter : object
        A :class:`VideoFilter`, or any callable (which is not deep).
    frame : Image
        The frame to filter.
    levels : tuple[float, float] or None
        The pixel values of *frame* that are black and white.

    Returns
    -------
    tuple
        The frame to give to the filter and the levels that belong to it.
    '''
    deep = getattr(video_filter, 'deep', False)
    if frame.dtype == np.uint16 and not deep:
        return to8bit(frame, levels), None
    if deep and isinstance(video_filter, VideoFilter):
        video_filter.levels = levels if frame.dtype == np.uint16 else None
    return frame, levels


class VideoFilter(QtCore.QObject):

    '''Base class for video filters.

    Provides a two-stage ``add``/``get`` interface so that subclasses
    can accumulate state across frames (e.g. running averages) before
    returning a result.  ``add`` stores the frame and ``get`` returns
    ``process`` of it; the default ``process`` is a passthrough, so a
    stateless filter only overrides :meth:`process`.

    The :meth:`__call__` operator chains :meth:`add` and :meth:`get`
    so that filters can be used as plain callables.

    A filter works on 8 bit frames.  The filter pipeline hands it a
    ``uint16`` frame (from a camera of more than 8 bits) only if the
    attribute :attr:`deep` is ``True``, which promises that the output has
    the scale of the input: the same black and white levels, which
    :meth:`bounds` returns.  Otherwise the pipeline first scales the frame
    to ``uint8`` between its levels.
    '''

    #: Whether the filter keeps the scale of a ``uint16`` frame.
    deep: bool = False

    #: The pixel values of a ``uint16`` frame that are black and white.
    #: The pipeline sets it before it calls a :attr:`deep` filter; it is
    #: ``None`` for an 8 bit frame and when no pipeline is involved.
    levels: tuple[float, float] | None = None

    def bounds(self, frame: Image) -> tuple[float, float]:
        '''Return the black and white values of *frame*.

        A :attr:`deep` filter uses these to keep the scale of its input:
        the :attr:`levels` of the camera, or the whole range of the type
        (0 to 255 for ``uint8``) if there are none.

        Parameters
        ----------
        frame : Image
            An integer frame.

        Returns
        -------
        tuple[float, float]
            The pixel values of black and white.
        '''
        if self.levels is not None and frame.dtype == np.uint16:
            return self.levels
        return 0., float(np.iinfo(frame.dtype).max)

    def __init__(self) -> None:
        super().__init__()
        self.data: Image | None = None

    def __call__(self, data: Image) -> Image | None:
        '''Apply the filter to *data* and return the result.

        Parameters
        ----------
        data : Image
            Input frame.

        Returns
        -------
        Image or None
            Filtered frame, or ``None`` if no result is available yet.
        '''
        self.add(data)
        return self.get()

    def add(self, data: Image) -> None:
        '''Incorporate a new frame into the filter state.

        Parameters
        ----------
        data : Image
            Input frame.
        '''
        self.data = data

    def get(self) -> Image | None:
        '''Return the current filter output.

        Returns
        -------
        Image
            Filtered frame.

        Raises
        ------
        RuntimeError
            If called before the first :meth:`add`.
        '''
        if self.data is None:
            raise RuntimeError('get() called before add()')
        return self.process(self.data)

    def process(self, data: Image) -> Image:
        '''Return the filtered version of *data*.

        A stateless filter overrides this and needs nothing else:
        :meth:`get` applies it to the frame stored by :meth:`add`.  The
        default is a passthrough.  A filter that accumulates state across
        frames overrides :meth:`add` and :meth:`get` instead.

        Parameters
        ----------
        data : Image
            Input frame.

        Returns
        -------
        Image
            Filtered frame.
        '''
        return data

    def to_code(self) -> FilterCode | None:
        '''Return a :class:`FilterCode` fragment for pipeline export.

        Stateless filters implement this to enable
        :meth:`~QVideo.lib.QFilterRack.QFilterRack.exportPipeline`.
        Stateful filters (those that accumulate state across frames)
        return ``None`` to indicate they cannot be expressed as a
        single-frame pure function.

        Returns
        -------
        FilterCode or None
            Code fragment, or ``None`` if export is not supported.
        '''
        return None


class QVideoFilter(QtWidgets.QGroupBox):

    '''Widget wrapper for a :class:`VideoFilter` with an enable checkbox.

    Displays the filter as a checkable
    :class:`~pyqtgraph.Qt.QtWidgets.QGroupBox`.
    When checked the filter is applied to incoming frames; when unchecked
    frames pass through unchanged.

    Subclasses can extend the UI by overriding :meth:`_setupUi`.  The
    override should call ``super()._setupUi()`` first, then add widgets
    to ``self._layout``.

    Subclasses should set :attr:`display_name` to a short human-readable
    label.  :class:`~QVideo.lib.QFilterRack.QFilterRack` uses
    this to populate the "Add filter…" picker.

    Parameters
    ----------
    parent : QtWidgets.QWidget
        Parent widget.
    title : str
        Label displayed in the group box border.
    videoFilter : VideoFilter
        The filter to apply when enabled.

    Class Attributes
    ----------------
    display_name : str
        Human-readable name shown in the filter picker.  Empty string
        means the filter will not appear in the picker.
    display_category : str
        Category label used to group filters in the picker tree.
        Defaults to ``'Other'`` in the picker when empty.
    '''

    display_name: str = ''
    display_category: str = ''

    def __init__(self,
                 parent: QtWidgets.QWidget | None,
                 title: str,
                 videoFilter: VideoFilter) -> None:
        super().__init__(title, parent)
        self._videoFilter = videoFilter
        self._setupUi()
        self._connectSignals()
        self.toggled.connect(self._clearError)

    @property
    def videoFilter(self) -> VideoFilter:
        '''The :class:`VideoFilter` applied when this widget is enabled.'''
        return self._videoFilter

    @videoFilter.setter
    def videoFilter(self, videoFilter: VideoFilter) -> None:
        if not isinstance(videoFilter, VideoFilter):
            raise TypeError(
                f'expected VideoFilter, got {type(videoFilter).__name__}')
        self._videoFilter = videoFilter

    def __call__(self, image: Image) -> Image | None:
        '''Apply the filter if enabled, otherwise return *image* unchanged.

        A filter that raises is logged once and switched off, so frames
        pass through unchanged until it is checked again.  Call from the
        GUI thread, as it changes the state of the widget.

        Parameters
        ----------
        image : Image
            Input frame.

        Returns
        -------
        Image or None
            Filtered frame if checked, otherwise *image* unchanged.
        '''
        if not self.isChecked():
            return image
        try:
            return self.videoFilter(image)
        except Exception as error:
            logger.exception(f'{type(self.videoFilter).__name__} failed and '
                             'was switched off')
            self.switchOff(error)
            return image

    def switchOff(self, error: Exception) -> None:
        '''Uncheck the filter and show *error* as the reason in its tooltip.

        Checking the filter again clears the message and retries it.

        Parameters
        ----------
        error : Exception
            The exception that made the filter fail.
        '''
        self.setToolTip(f'Switched off after an error: {error}')
        self.setChecked(False)

    def _setupUi(self) -> None:
        '''Configure the group box and create the horizontal layout.

        Subclasses should call ``super()._setupUi()`` and then add their
        own widgets to ``self._layout``.
        '''
        self.setCheckable(True)
        self.setChecked(False)
        self.setFlat(True)
        self._layout = QtWidgets.QHBoxLayout(self)
        self._layout.setContentsMargins(2, 5, 2, 5)

    def _connectSignals(self) -> None:
        '''Connect signals for UI elements

        Subclasses should call ``super()._connectSignals()`` and then
        connect their own signals.
        '''

    def _clearError(self, checked: bool) -> None:
        '''Remove the failure message when the filter is switched on again.'''
        if checked:
            self.setToolTip('')

    @classmethod
    def example(cls: type[QVideoFilter]) -> None:  # pragma: no cover
        '''Demonstrate the filter widget.

        Intended to be called on a concrete subclass that supplies its
        own ``__init__`` defaults, not on :class:`QVideoFilter` directly.
        '''
        pg.mkQApp()
        widget = cls()
        widget.show()
        pg.exec()
